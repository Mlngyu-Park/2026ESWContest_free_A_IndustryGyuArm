/* ============================================================
 *  DUSK 노드 커널 — 정수 전용
 *
 *  68000 에는 FPU 가 없다. 이 파일에는 float / double 이 한 글자도
 *  없어야 한다 (있으면 68000 에서 못 돈다).
 *
 *  고정소수점 규약
 *    q15_t  활성값.  1.0 = 32767.  범위 -1.0 ~ +0.99997
 *    q31_t  누산기.  MULS 결과를 32비트로 모은다.
 *
 *  나눗셈·제곱근·exp 는 68000 에서 비싸거나 아예 없다.
 *    · 나눗셈 → DIVS (158 사이클) 를 최소한만
 *    · 제곱근 → 뉴턴 반복 3회 (정수)
 *    · exp    → 2의 거듭제곱 + 룩업 (곱셈·시프트만)
 * ============================================================ */
#include "dusk.h"
#include <string.h>
#include <stdio.h>
#include <stdlib.h>

/* ── MAC 한 줄 ─────────────────────────────────────────────
 *  y = Σ w[i] * x[i]
 *  68000 의 MULS.W 는 16×16→32 다. 가중치는 int8 이라 부호확장해서 쓴다.
 *  누산은 32비트(ADD.L). 320개를 더해도 넘치지 않는다:
 *    최악 127 * 32767 * 320 = 1.33e9 < 2^31 (2.15e9)
 */
int32_t dusk_mac_row(const int8_t *w, const q15_t *x, int n)
{
    /* ★★ int64 로 누산한다 — 실측으로 잡은 버그:
         int8(±127) × q15(±32767) 를 1280개(mlp.2 의 cols) 더하면
         최악 53억 으로 int32(21억)를 넘어 부호가 뒤집힌다.
         320개(±13억)는 안전해서 앞 층은 멀쩡한데 mlp.2 만 깨졌다.

       68000 관점: MULS 는 16×16→32 라 곱셈은 문제없다. 누산만
       32비트 두 개로 나눠 ADD.L + ADDX.L 하면 된다 — 68000 이 큰 수를
       다루는 원래 방식이고, 비용은 MAC 당 ADDX.L 한 번(8T)뿐이다. */
    int64_t acc = 0;
    int i = 0;
    /* 4개씩 펼친다 — mac_68k.s 와 같은 구조 (DBRA 부담을 1/4 로) */
    for (; i + 3 < n; i += 4) {
        acc += (int64_t)w[i    ] * (int32_t)x[i    ];
        acc += (int64_t)w[i + 1] * (int32_t)x[i + 1];
        acc += (int64_t)w[i + 2] * (int32_t)x[i + 2];
        acc += (int64_t)w[i + 3] * (int32_t)x[i + 3];
    }
    for (; i < n; i++)
        acc += (int64_t)w[i] * (int32_t)x[i];

    if (acc >  2147483647LL) acc =  2147483647LL;
    if (acc < -2147483648LL) acc = -2147483648LL;
    return (int32_t)acc;
}

/* ── 누산기(q31) → 활성값(q15) 재양자화 ────────────────────
 *  32비트 누산 결과를 다음 층 입력인 int16 으로 줄인다.
 *  가장 큰 값이 q15 최대(32767)가 되도록 시프트 양을 정한다.
 *
 *  나눗셈을 안 쓰고 시프트만 쓴다 — 68000 에서 DIVS 는 158 사이클,
 *  ASR 은 8 사이클이다. 정밀도를 조금 잃는 대신 20배 빠르다.
 */
void dusk_quant(const q31_t *in, q15_t *out, int n, int32_t *shift_out)
{
    /* 최댓값의 절댓값 찾기 */
    int32_t mx = 0;
    for (int i = 0; i < n; i++) {
        int32_t v = in[i] < 0 ? -in[i] : in[i];
        if (v > mx) mx = v;
    }
    if (mx == 0) {
        memset(out, 0, (size_t)n * sizeof(q15_t));
        if (shift_out) *shift_out = 0;
        return;
    }
    /* mx 를 32767 이하로 만드는 최소 시프트 */
    int sh = 0;
    while ((mx >> sh) > 32767) sh++;

    for (int i = 0; i < n; i++) {
        int32_t v = in[i] >> sh;
        if (v >  32767) v =  32767;
        if (v < -32768) v = -32768;
        out[i] = (q15_t)v;
    }
    if (shift_out) *shift_out = sh;
}

/* ── 정수 제곱근 (뉴턴 반복) ───────────────────────────────
 *  68000 에 sqrt 명령이 없다. LayerNorm 의 표준편차에 필요하다.
 *  나눗셈 3번이면 32비트 범위에서 충분히 수렴한다.
 */
static int32_t isqrt32(int32_t v)
{
    if (v <= 0) return 0;
    /* 초기값: 최상위 비트의 절반 자리 */
    int32_t x = v, b = 0;
    while (x > 0) { x >>= 2; b++; }
    x = (int32_t)1 << b;                 /* 대략 sqrt(v) */
    /* 뉴턴: x = (x + v/x) / 2 */
    for (int i = 0; i < 4 && x > 0; i++)
        x = (x + v / x) >> 1;
    return x;
}

/* ── LayerNorm (정수) ──────────────────────────────────────
 *  y = (x - 평균) / 표준편차 * g + b
 *
 *  나눗셈이 두 번 필요한데(평균, 표준편차) 68000 에서 DIVS 는 비싸다.
 *  평균은 n 이 320 처럼 고정이면 곱셈+시프트로 바꿀 수 있지만,
 *  여기서는 일반성을 위해 DIVS 를 쓴다. 층당 2회뿐이라 부담이 적다.
 *
 *  g, b 는 int8 가중치 + 스케일(gs, bs)로 온다.
 */
/* LayerNorm.
   ★ gs, bs 는 '시프트량' 이 아니라 q16 스케일 정수다 (scale * 65536).
     전에는 시프트량으로 받았는데, 2의 거듭제곱으로만 근사되어
     원소마다 다른 오차가 생겼다. */
void dusk_layernorm_q(q15_t *x, const int8_t *g, const int8_t *b, int n,
                      int32_t gs, int32_t bs)
{
    if (n <= 0) return;

    /* ① 평균 */
    int32_t sum = 0;
    for (int i = 0; i < n; i++) sum += x[i];
    int32_t mean = sum / n;                      /* DIVS 1회 */

    /* ② 분산 — 편차 제곱의 평균.
       편차가 q15 라 제곱하면 q30 이 된다. 넘치지 않게 미리 줄인다. */
    int32_t var = 0;
    for (int i = 0; i < n; i++) {
        int32_t d = (int32_t)x[i] - mean;
        var += (d * d) >> 8;                     /* q30 -> q22 */
    }
    var /= n;                                    /* DIVS 1회 */

    /* ③ 표준편차. var 가 q22 이므로 sqrt 하면 q11 이 된다. */
    int32_t sd = isqrt32(var);
    if (sd < 1) sd = 1;                          /* 0 나눗셈 방지 */

    /* ④ 정규화 + 스케일.
       (d << 11) / sd 가 q15 정규화값 (sd 가 q11 이므로).

       ★ gamma/beta 를 시프트로 적용하면 안 된다 — 실측:
         시프트는 2의 거듭제곱만 되므로 gamma 1.0001 을 0.9141 로
         근사한다 (9% 오차). 게다가 원소마다 오차가 달라서
         "원소마다 다르게 틀리는" 증상이 나온다 (실측: 비율 2.16~3.83).

         scale 은 q16 정수이므로 곱하고 >>16 하면 정확하다.
         68000 에서 MULS 는 70T — 시프트보다 비싸지만 정확도가 우선이고,
         LayerNorm 은 층당 320개뿐이라 전체 비용에서 무시할 수준이다
         (행렬곱은 층당 100만 번이다). */
    for (int i = 0; i < n; i++) {
        int32_t dv = (int32_t)x[i] - mean;
        /* ★ q15 로 두면 ±1.0 까지만 담긴다. 그런데 정답의 LayerNorm
             출력은 ±3σ 까지 나온다 (실측: 1.6788 이 1.0000 에 포화됐다).
             그래서 1/4 로 줄여 담는다 (±4.0 까지). 이 배율은 다음
             단계의 dusk_norm 이 다시 맞춰주므로 정보는 안 잃는다. */
        int32_t norm = (int32_t)(((int64_t)dv << 9) / sd);    /* q15 의 1/4 */

        /* gamma = g[i] * gs / 65536.  곱하고 >>16 (정확) */
        int64_t y64 = (int64_t)norm * g[i] * gs;
        y64 >>= 16;
        /* beta = b[i] * bs / 65536 을 q15 로 올린다 */
        y64 += ((int64_t)b[i] * bs * 32768) >> 16;
        int32_t y = (int32_t)y64;

        if (y >  32767) y =  32767;
        if (y < -32768) y = -32768;
        x[i] = (q15_t)y;
    }
}

/* ── GELU (정수 근사) ──────────────────────────────────────
 *  진짜 GELU 는 erf 가 필요하다. 68000 에서는 불가능하다.
 *  tanh 근사식도 exp 가 들어간다.
 *
 *  대신 조각별 선형(piecewise linear)으로 근사한다.
 *  최대 오차 0.02 정도인데, 이 모델은 출력이 이산(글자)이라
 *  그 정도는 결과를 안 바꾼다 — 검증으로 확인할 것.
 *
 *    x <= -2.0        →  0
 *    -2.0 < x < 0     →  x * (x+2)/4       (부드럽게 0 으로)
 *    0 <= x < 2.0     →  x * (x+2)/4 ... 대칭이 아니므로 아래 표 사용
 *    x >= 2.0         →  x
 */
#include "gelu_tab.h"

/* GELU — 표에서 찾는다. 입력·출력 모두 'Q15 의 1/4' 규약 (32768 = 4.0).
   상위 8비트로 표를 찾고 나머지로 선형보간한다. */
void dusk_gelu_q(q15_t *x, int n)
{
    for (int i = 0; i < n; i++) {
        int32_t v = x[i];
        int32_t k = v >> 7;                    /* -256 .. 255 */
        int32_t f = v & 127;                   /* 보간용 나머지 */
        int32_t a = GELU_TAB[k & 511];
        int32_t b = GELU_TAB[(k + 1) & 511];
        x[i] = (q15_t)(a + (((b - a) * f) >> 7));
    }
}

/* 2^f 의 소수부 룩업 (f = 0 ~ 15/16), q15 로 저장.
   2^0=1.0 → 32767, 2^(15/16)=1.917 → 넘치므로 절반 스케일(q14)로 둔다. */
static const uint16_t POW2_FRAC[16] = {
    16384, 17102, 17850, 18631, 19446, 20296, 21183, 22110,
    23078, 24088, 25144, 26247, 27400, 28605, 29864, 31182
};

/* exp(x) 근사. x 는 q15 (범위 -1 ~ 0 을 기대), 결과는 q15. */
/* exp(x) 를 정수로. 입력은 Q11 (1.0 = 2048), 출력은 Q15.

   ★ 왜 Q11 인가 — 실측으로 정한 것:
     C++ 원본의 어텐션 점수 폭을 재보니 0.9 ~ 5.5 였다 (문장 하나에서).
     Q15 는 ±1.0 밖에 못 담아서, 점수를 Q15 에 억지로 넣으면 폭이
     1 미만으로 눌린다. 그러면 exp 차이가 거의 없어져 어텐션이
     완전히 균등해진다 — 실측으로 최대=최소=균등값이 나왔다.
     Q11 은 ±16 을 담으므로 실제 점수 폭을 살릴 수 있다.

   x 는 항상 <= 0 이다 (softmax 에서 최댓값을 뺀 뒤 호출한다). */
static int32_t exp_q(int32_t x)
{
    if (x >= 0) return 32767;
    if (x <= -2048 * 12) return 0;        /* exp(-12) = 6e-6, 사실상 0 */

    /* x * log2(e) : Q11 곱셈 (1.4427 * 2048 = 2955) */
    int32_t e = (x * 2955) >> 11;         /* Q11, 음수 */
    int32_t ip = (-e) >> 11;              /* 정수부 */
    int32_t fp = (-e) & 2047;             /* 소수부 (Q11) */
    if (ip > 14) return 0;

    /* 2^-fp 를 표에서. fp 를 Q15 로 올려 기존 표(16칸)를 쓴다. */
    /* 2^(1-fp) 를 표에서. 표는 16칸이라 계단 오차가 칸당 최대 4.4% —
       어텐션 출력 오차 1.5% 의 주범이었다. 두 칸 사이를 선형보간한다.
       68000 비용: MULS 한 번(70T). 표 32칸으로 늘리는 것보다 정확하다. */
    int32_t u   = (2047 - fp) << 4;       /* (1-fp) 를 Q15 로: 0..32752 */
    int idx     = u >> 11;                /* 0..15 */
    int32_t fr  = u & 2047;               /* 칸 안의 위치 (Q11) */
    if (idx < 0) idx = 0;
    if (idx > 15) idx = 15;
    int32_t m0 = POW2_FRAC[idx];
    int32_t m1 = idx < 15 ? POW2_FRAC[idx + 1] : 32768;   /* 2^1 = 2.0 q14 */
    int32_t m  = m0 + (((m1 - m0) * fr) >> 11);           /* q14 = 2^(1-fp) */
    /* ★ 2^-(ip+fp) = 2^(1-fp) / 2^(ip+1).  전에는 (m<<1)>>ip 로 마지막
         /2 를 빠뜨려 값이 정확히 2배였다 (실측: exp(-0.743) 이 0.476
         이어야 하는데 0.917). softmax 가 납작해져 정수 확률비가
         2.1 대신 1.1 로 나온 원인. q14 m 을 q15 로 보면 이미 x2 이므로
         >>ip 만 하면 된다 (= m*2 / 2^(ip+1)). */
    int32_t r = m >> ip;
    if (r > 32767) r = 32767;
    return r;
}

/* Softmax. ★ 입력 x 는 Q11 (1.0=2048) 인 '점수' 이고,
   출력은 Q15 (합계 32767) 인 '확률' 이다. 단위가 바뀐다.
   입력을 Q11 로 받는 이유는 exp_q 주석 참조. */
void dusk_softmax_q(q15_t *x, int n)
{
    if (n <= 0) return;

    /* ① 최댓값 빼기 (넘침 방지 — 진짜 softmax 도 이렇게 한다) */
    int32_t mx = x[0];
    for (int i = 1; i < n; i++) if (x[i] > mx) mx = x[i];

    /* ② exp */
    int32_t sum = 0;
    /* 노드 하나가 다루는 어텐션 길이는 문맥(256)이 최대다 */
    /* ★ ctx 가 448(v9)로 늘었다. 256 으로 자르면 뒤쪽 위치의 어텐션이
         통째로 사라진다 — 긴 답이 틀리는 조용한 원인이 된다. */
    static int32_t e[512];
    int m = n > 512 ? 512 : n;
    for (int i = 0; i < m; i++) {
        e[i] = exp_q((int32_t)x[i] - mx);
        sum += e[i];
    }
    if (sum <= 0) {                        /* 전부 0 이면 균등분포 */
        int32_t v = 32767 / m;
        for (int i = 0; i < m; i++) x[i] = (q15_t)v;
        return;
    }

    /* ③ 정규화 — DIVS 를 n 번 쓰는 대신, 역수를 한 번 구해 곱한다.
       68000 에서 DIVS 158 사이클 × 256 = 40,448 사이클이 되므로
       역수 1회(158) + MULS 256회(70) = 18,078 사이클로 줄인다. */
    int32_t inv = (32767 << 15) / sum;     /* q15 역수, DIVS 1회 */
    for (int i = 0; i < m; i++) {
        int32_t v = (e[i] * inv) >> 15;
        if (v > 32767) v = 32767;
        x[i] = (q15_t)v;
    }
    for (int i = m; i < n; i++) x[i] = 0;
}

/* ============================================================
 *  블록 부동소수점 연산 — 지수를 함께 다룬다
 *
 *  왜 필요한가: dusk.h 의 DuskVec 주석 참조.
 *  요약하면 RACHEL 잔차가 층마다 2.7배 자라는데 Q15 로는 ±1 밖에
 *  못 담아서, 값과 지수를 따로 들고 다닌다.
 * ============================================================ */

/* 누산기(q31)를 Q15 로 정규화하고 지수를 돌려준다.

   ★ 기준을 '최대값' 이 아니라 'rms' 로 잡는다 — 실측으로 정한 것:
     최대값을 Q15 상한에 맞추면, 이상치 하나가 벡터 전체를 눌러버린다.
     C++ 정답을 계측해 보니 잔차의 최대/rms 비가 층마다 2.7~3.1 로
     들쭉날쭉했다. 최대값 기준으로 맞추면 그 변동이 그대로 배율 오차가
     되어 층마다 누적된다 (실측: 층당 1.11배씩 벌어져 L7 에서 5.5배).

     rms 를 기준으로 하면 벡터의 '전체적인 크기' 에 맞춰지므로
     이상치에 흔들리지 않는다. rms 를 8192(=0.25)에 두어
     최대값(보통 rms의 3배)이 Q15 상한에 여유있게 들어가게 한다.

   in_exp: 입력이 갖고 있던 지수 (여기에 시프트량을 더해 나간다) */
int dusk_norm(const q31_t *in, q15_t *out, int n, int in_exp)
{
    if (n <= 0) return in_exp;

    /* rms 를 구한다. 제곱합은 int64 로 받는다 (q31 제곱은 int32 초과) */
    int64_t ss = 0;
    int32_t mx = 0;
    for (int i = 0; i < n; i++) {
        int64_t v = in[i];
        ss += v * v;
        int32_t a = in[i] < 0 ? -in[i] : in[i];
        if (a > mx) mx = a;
    }
    if (mx == 0) {
        memset(out, 0, (size_t)n * sizeof(q15_t));
        return in_exp;
    }
    /* rms = sqrt(ss/n). 68000 에서도 정수 제곱근 한 번이다. */
    uint32_t ms = (uint32_t)(ss / n > 0xFFFFFFFFLL ? 0xFFFFFFFFLL : ss / n);
    uint32_t rms = isqrt32(ms);
    if (rms == 0) rms = 1;

    /* rms 를 목표값에 맞춘다. 시프트만 쓴다 (68000 에서 나눗셈은 158T).

       ★ 버그를 잡은 자리 — 실측:
         입력 100.0 을 넣었더니 q15 = -32768 (음수!) 이 나왔다.
         rms 가 목표보다 작다고 보고 왼쪽으로 밀었는데, 큰 값이
         int32 부호 비트를 침범해 음수가 됐다.
         잔차는 층마다 자라므로 이 버그가 뒤로 갈수록 심해진다.

       그래서 왼쪽 시프트는 '최대값' 을 기준으로 한계를 둔다.
       rms 를 맞추려다 최대값이 넘치면 안 된다. */
    const int32_t TARGET = 8192;
    int right = 0, left = 0;

    if ((int32_t)rms > TARGET) {
        while ((int32_t)(rms >> right) > TARGET && right < 30) right++;
    } else {
        /* 왼쪽으로 밀되, 최대값이 Q15 상한을 넘지 않는 선까지만 */
        while (left < 30
               && (int32_t)(rms << (left + 1)) <= TARGET
               && (mx >> 0) <= (32767 >> (left + 1)))
            left++;
    }

    /* 최종 확인: 이상치가 Q15 를 넘으면 오른쪽으로 더 민다.
       (잘라내면 정보가 사라지므로 지수를 조정한다) */
    while (left > 0 && (mx << left) > 32767) left--;
    while ((right < 30) && ((mx >> right) > 32767)) right++;

    int clipped = 0;
    for (int i = 0; i < n; i++) {
        int32_t v = right ? (in[i] >> right) : (in[i] << left);
        if (v >  32767) { v =  32767; clipped++; }
        if (v < -32768) { v = -32768; clipped++; }
        out[i] = (q15_t)v;
    }
    if (clipped && getenv("DUSK_CLIP"))
        fprintf(stderr, "  [포화] dusk_norm n=%d 중 %d개 잘림 (%.1f%%)\n",
                n, clipped, 100.0*clipped/n);
    return in_exp + right - left;
}

/* 두 벡터를 더한다 (지수가 다를 수 있다 — 잔차 연결에 쓴다).
   ★ 이게 핵심이다. 큰 쪽 지수에 맞추고 작은 쪽을 밀어 더한다.
     그래서 층 간 성장이 그대로 살아난다.

   ★★ 정밀도 주의 — 실측으로 배운 것:
      처음에는 더한 뒤 무조건 >>1 하고 지수를 +1 했다. 그러면 층마다
      값이 반씩 줄어 L7 에서 최대값이 3 밖에 안 남았다 (정보 소실).
      실제 잔차 성장은 층당 1.14배(2.7배를 7층에 나눈 것)뿐이다.

      그래서 q31 로 정확히 더한 뒤 dusk_norm 으로 다시 꽉 채운다.
      68000 비용: 벡터 한 번 더 훑기 — MAC 수십만 번에 비하면 무시할
      수준이다. */
int dusk_vadd(q15_t *a, int a_exp, const q15_t *b, int b_exp, int n)
{
    int hi = a_exp > b_exp ? a_exp : b_exp;
    int sa = hi - a_exp, sb = hi - b_exp;
    if (sa > 30) sa = 30;
    if (sb > 30) sb = 30;

    /* q31 로 정확히 더한다 */
    static q31_t tmp[8192];
    int m = n > 8192 ? 8192 : n;
    int32_t mx = 0;
    for (int i = 0; i < m; i++) {
        tmp[i] = ((q31_t)a[i] >> sa) + ((q31_t)b[i] >> sb);
        int32_t t = tmp[i] < 0 ? -tmp[i] : tmp[i];
        if (t > mx) mx = t;
    }

    /* ★ 잔차는 정규화하지 않는다 — 실측으로 배운 것:
         rms 를 매번 같은 값에 맞추면 층 간 성장이 통째로 지워진다
         (실측: 8개 층 모두 rms 0.1585 로 똑같아졌다). 앞서 >>1 로
         깎았을 때와 같은 결과다.

         잔차의 성장 자체가 정보다 (C++ 실측: L0 2.48 -> L7 6.72).
         그러니 지수는 그대로 두고 값이 자라게 놔둔다.
         Q15 를 넘칠 때만 한 칸 줄이고 지수를 올린다 — 자릿수를
         지키는 최소한의 개입이다. */
    int shift = 0;
    while ((mx >> shift) > 32767 && shift < 30) shift++;

    for (int i = 0; i < m; i++) {
        int32_t v = tmp[i] >> shift;
        if (v >  32767) v =  32767;
        if (v < -32768) v = -32768;
        a[i] = (q15_t)v;
    }
    return hi + shift;
}

/* LayerNorm 은 스케일을 없앤다 — 출력 지수가 입력과 무관해진다.
   (평균을 빼고 표준편차로 나누므로 결과는 항상 ±몇 배 안이다)
   그래서 지수를 고정값으로 돌려주면 된다. 이게 지수 추적을 단순하게
   만드는 지점이다 — 층마다 LayerNorm 이 지수를 초기화해 준다. */


/* ── int32 점수용 softmax ────────────────────────────────
   ★ 왜 따로 있나 — 실측으로 잡은 버그:
     점수를 int16(Q11, ±16) 에 담으면 뾰족한 헤드에서 상한을 넘는
     위치가 생긴다 (L4 에서 헤드당 7~9개 클램프). 그러면 상위 점수들의
     순서가 뭉개져 어텐션 출력 오차가 65% 까지 튀었다.
     점수를 int32 로 그대로 받으면 클램프가 없다. exp_q 는 입력이
     -12.0 이하면 0 을 돌려주므로 아주 작은 값은 자연히 사라진다.

   입력 x[]: Q11 점수 (int32, 클램프 없음)
   출력 x[]: Q15 확률 (합 ≈ 32767)
   정규화: 역수를 q20 으로 한 번 구해 곱하고 반올림한다.
     — >>15 내림을 쓰면 위치 150개 x 1단위씩 확률 질량이 샌다.
     68000: DIVS 1회 + 위치당 32x32 곱셈(MULS 여러 번) — 위치당
     DIVS(158T) 보다 싸다. */
void dusk_softmax_q32(int32_t *x, int n)
{
    if (n <= 0) return;
    int32_t mx = x[0];
    for (int i = 1; i < n; i++) if (x[i] > mx) mx = x[i];

    int64_t sum = 0;
    for (int i = 0; i < n; i++) {
        int64_t dlt = (int64_t)x[i] - mx;          /* <= 0 */
        if (dlt < -2147483647LL) dlt = -2147483647LL;
        x[i] = exp_q((int32_t)dlt);                /* Q15, 0..32767 */
        sum += x[i];
    }
    if (sum <= 0) { int32_t v = 32767 / n; for (int i = 0; i < n; i++) x[i] = v; return; }

    int64_t inv = ((int64_t)32767 << 20) / sum;    /* q20 역수, 나눗셈 1회 */
    for (int i = 0; i < n; i++) {
        int64_t v = ((int64_t)x[i] * inv + (1LL << 19)) >> 20;   /* 반올림 */
        if (v > 32767) v = 32767;
        x[i] = (int32_t)v;
    }
}
